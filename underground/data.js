// ── 幾何判斷與比對
export function inZone(z, x, y, m = 0) {
  if (z.rect) { const [a, b, c, d] = z.rect; return x >= a - m && x <= c + m && y >= b - m && y <= d + m; }
  for (let i = 0; i < z.path.length - 1; i++) {
    const [a, b] = z.path[i], [c, d] = z.path[i + 1], vx = c - a, vy = d - b;
    const t = Math.max(0, Math.min(1, ((x - a) * vx + (y - b) * vy) / (vx * vx + vy * vy)));
    if (Math.hypot(x - a - vx * t, y - b - vy * t) <= z.w / 2 + m) return true;
  } return false;
}
export const zonesAt = (lv, x, y, m = 0) => ZONES.filter(z => z.level === lv && inZone(z, x, y, m));
function samples(z) { const p = []; if (z.rect) { const [a, b, c, d] = z.rect; for (let x = a; x <= c; x += 12) for (let y = b; y <= d; y += 12) p.push([x, y]); p.push([c, d], [a, d], [c, b]); } else for (let i = 0; i < z.path.length - 1; i++) for (let t = 0; t <= 1; t += .05) p.push(along(z.path[i], z.path[i + 1], t)); return p; }
export function check() {
  const issues = [], M = 16;   // 容許誤差 16 px（約 9 m）
  for (const e of EXITS) if (!zonesAt(e.level, e.x, e.y, M).length) issues.push(`出口 ${e.id}：${e.level} 沒有對應的區域`);
  for (const s of STAIRS) for (const lv of s.levels) if (lv !== "G" && !zonesAt(lv, s.x, s.y, M).length) issues.push(`樓梯 ${s.id}：${lv} 沒有對應的區域`);
  const ids = new Set(); for (const o of [...EXITS, ...STAIRS, ...ZONES]) { if (ids.has(o.id)) issues.push(`編號重複：${o.id}`); ids.add(o.id); }
  // 連通：同層相鄰＋樓梯；每個區域都要能從某個出口走到
  const adj = new Map(ZONES.map(z => [z.id, new Set()])); const S = new Map(ZONES.map(z => [z.id, samples(z)]));
  for (const a of ZONES) for (const b of ZONES) if (a !== b && a.level === b.level && S.get(a.id).some(([x, y]) => inZone(b, x, y, M))) { adj.get(a.id).add(b.id); adj.get(b.id).add(a.id); }
  for (const s of STAIRS) { const zs = s.levels.filter(l => l !== "G").flatMap(l => zonesAt(l, s.x, s.y, M)); for (const a of zs) for (const b of zs) if (a !== b) adj.get(a.id).add(b.id); }
  const seen = new Set(), q = EXITS.flatMap(e => zonesAt(e.level, e.x, e.y, M).map(z => z.id));
  while (q.length) { const id = q.pop(); if (seen.has(id)) continue; seen.add(id); q.push(...adj.get(id)); }
  for (const z of ZONES) if (!seen.has(z.id)) issues.push(`區域 ${z.name}（${z.level}）：從任何出口都走不到`);
  const perLevel = {}; for (const lv of LEVELS) perLevel[lv] = { zones: ZONES.filter(z => z.level === lv).length, exits: lv === "G" || lv === "B1" ? EXITS.length : 0, stairs: STAIRS.filter(s => s.levels.includes(lv)).length };
  return { issues, perLevel, adj };
}
